"""
Fusion export: one self-contained Fusion script per model (table-driven, no numpy needed in Fusion).

The model's exact curves are sampled at its own section heights into a table (z, r0, twist, ρ(θ) samples).
The script draws each section's base curve (fitted spline through 51 points, like create_polar_rose_spline),
places the teeth with the model's rule (arc length / equal angle with a half tooth at 0°), and lofts each tooth
through all sections (same as loft_triangle_wedges2). One quarter is built, like Grasshoper_full.

export(model_dir) -> models/<model>/fusion/<ID>/<ID>.py + .manifest  (add that folder in Fusion's Scripts dialog)
"""
import os, json
import numpy as np
import geometry as G
from bases import TH

NS = 181          # ρ samples per section over 0..90° (0.5°)

SCRIPT = r'''"""
Fusion script generated by models/_common/fusion_template.py — {ID}: {TITLE}
Kernel v{KERNEL}. Do not edit the table by hand; re-export from the model instead.
Builds ONE quarter: {N} teeth x {NSEC} sections, placement '{PLACEMENT}', apex height {H} mm.
"""
import adsk.core, adsk.fusion, traceback, math

N_TEETH = {N}
H_MM = {H}
PLACEMENT = '{PLACEMENT}'
TARGET_W_MM = {TW}
FILL = {FILL}
# (z mm, r0 mm, twist deg, rho samples over 0..90 deg in 0.5 deg steps)
SECTIONS = {SECTIONS}


def section_xy(r0, tw, rho, th):
    a = math.radians(tw)
    x, y = r0 * rho * math.cos(th), r0 * rho * math.sin(th)
    return x * math.cos(a) - y * math.sin(a), x * math.sin(a) + y * math.cos(a)


def interp(x, xs, ys):
    if x <= xs[0]: return ys[0]
    if x >= xs[-1]: return ys[-1]
    lo, hi = 0, len(xs) - 1
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if xs[mid] <= x: lo = mid
        else: hi = mid
    t = (x - xs[lo]) / (xs[hi] - xs[lo]) if xs[hi] > xs[lo] else 0.0
    return ys[lo] + t * (ys[hi] - ys[lo])


def teeth(r0, tw, rho):
    """[(p1, [4 arc pts], p2, apex)] in mm, world XY (same maths as models/_common/geometry.py)."""
    n = len(rho)
    ths = [0.5 * math.pi * i / (n - 1) for i in range(n)]
    S = [0.0]
    for i in range(1, n):
        x0, y0 = rho[i - 1] * math.cos(ths[i - 1]), rho[i - 1] * math.sin(ths[i - 1])
        x1, y1 = rho[i] * math.cos(ths[i]), rho[i] * math.sin(ths[i])
        S.append(S[-1] + math.hypot(x1 - x0, y1 - y0))
    out = []
    for i in range(N_TEETH):
        if PLACEMENT == 'arc':
            L = r0 * S[-1]
            if L < N_TEETH * TARGET_W_MM:
                W, g = L / N_TEETH, 0.0
            else:
                W, g = TARGET_W_MM, (L - N_TEETH * TARGET_W_MM) / (N_TEETH - 1)
            Wf = FILL * W
            s0 = i * (W + g) + (W - Wf) / 2
            th = [interp((s0 + Wf * k / 5) / r0, S, ths) for k in range(6)]
        else:
            Wd = 0.5 * math.pi / (N_TEETH - 0.5)
            if i == 0:
                a0, w = 0.0, Wd / 2
            else:
                w = Wd
                a0 = Wd / 2 + (i - 1) * Wd + (w - FILL * w) / 2
            w = FILL * w
            th = [a0 + w * k / 5 for k in range(6)]
        P = [section_xy(r0, 0.0, interp(t, ths, rho), t) for t in th]
        dx, dy = P[-1][0] - P[0][0], P[-1][1] - P[0][1]
        l = math.hypot(dx, dy)
        if PLACEMENT != 'arc' and i == 0:
            apex = (P[0][0] + H_MM, P[0][1])
        else:
            apex = ((P[0][0] + P[-1][0]) / 2 + H_MM * dy / l, (P[0][1] + P[-1][1]) / 2 - H_MM * dx / l)
        a = math.radians(tw)
        rot = lambda p: (p[0] * math.cos(a) - p[1] * math.sin(a), p[0] * math.sin(a) + p[1] * math.cos(a))
        out.append(([rot(p) for p in P], rot(apex)))
    return out


def loft_wedges(rootComp, sketches):
    loft_features = rootComp.features.loftFeatures
    stacks, nw = [], 0
    for sk in sketches:
        prs = []
        for prof in sk.profiles:
            bb = prof.boundingBox
            ang = math.degrees(math.atan2((bb.minPoint.y + bb.maxPoint.y) / 2, (bb.minPoint.x + bb.maxPoint.x) / 2)) % 360
            prs.append((ang, prof))
        if not prs: continue
        if max(a for a, _ in prs) - min(a for a, _ in prs) > 180:
            prs.sort(key=lambda x: x[0] + 360 if x[0] < 180 else x[0])
        else:
            prs.sort(key=lambda x: x[0])
        if nw == 0:
            nw = len(prs); stacks = [[] for _ in range(nw)]
        if len(prs) == nw:
            for i in range(nw): stacks[i].append(prs[i][1])
    for st in stacks:
        if len(st) >= 2:
            li = loft_features.createInput(adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
            li.isSolid = True
            for pr in st: li.loftSections.add(pr)
            try: loft_features.add(li)
            except: pass


def run(context):
    ui = None
    try:
        app = adsk.core.Application.get(); ui = app.userInterface
        root = adsk.fusion.Design.cast(app.activeProduct).rootComponent
        sketches = []
        P3 = lambda p: adsk.core.Point3D.create(p[0] / 10.0, p[1] / 10.0, 0)
        for z, r0, tw, rho in SECTIONS:
            pi = root.constructionPlanes.createInput()
            pi.setByOffset(root.xYConstructionPlane, adsk.core.ValueInput.createByReal(z / 10.0))
            plane = root.constructionPlanes.add(pi); plane.isLightBulbOn = False
            sk = root.sketches.add(plane); sk.isLightBulbOn = False
            sk.isComputeDeferred = True
            pts = adsk.core.ObjectCollection.create()
            n = len(rho)
            for k in range(51):
                th = 0.5 * math.pi * k / 50
                pts.add(P3(section_xy(r0, tw, interp(th, [0.5 * math.pi * i / (n - 1) for i in range(n)], rho), th)))
            sp = sk.sketchCurves.sketchFittedSplines.add(pts); sp.isConstruction = True
            lines = sk.sketchCurves.sketchLines; fs = sk.sketchCurves.sketchFittedSplines
            for P, apex in teeth(r0, tw, rho):
                l1 = lines.addByTwoPoints(P3(P[0]), P3(apex))
                l2 = lines.addByTwoPoints(l1.endSketchPoint, P3(P[-1]))
                c = adsk.core.ObjectCollection.create()
                c.add(l1.startSketchPoint)
                for p in P[1:-1]: c.add(P3(p))
                c.add(l2.endSketchPoint)
                fs.add(c)
            sk.isComputeDeferred = False
            sketches.append(sk)
        loft_wedges(root, sketches)
        ui.messageBox('{ID}: {NSEC} sections built. Run DumpCanvas to measure.')
    except:
        if ui: ui.messageBox('Failed:\n{{}}'.format(traceback.format_exc()))
'''

MANIFEST = {"autodeskProduct": "Fusion", "type": "script", "author": "", "description": {"": ""}, "version": "",
            "supportedOS": "windows|mac", "editEnabled": True}


def export(model, p, model_dir, kernel=1):
    sh = model.shape(p); st = model.SETTINGS
    zs = G.section_heights(sh, st)
    tb = G.Tables(sh, zs)
    th = np.linspace(0, np.pi / 2, NS)
    rows = []
    for i, z in enumerate(zs):
        rho = np.interp(th, TH, tb.rho[i])
        rows.append((round(float(z), 4), round(float(tb.r0[i]), 4), round(float(tb.rot[i]), 4), [round(float(v), 6) for v in rho]))
    body = "[\n" + ",\n".join(f"    ({a}, {b}, {c}, {d})" for a, b, c, d in rows) + ",\n]"
    code = SCRIPT.format(ID=model.ID, TITLE=model.TITLE, KERNEL=kernel, N=int(st['N']), H=float(st['H']),
                         PLACEMENT=st.get('placement', 'arc'), TW=float(st.get('target_w', 9.0)), FILL=float(st.get('fill', 1.0)),
                         NSEC=len(zs), SECTIONS=body)
    out = os.path.join(model_dir, 'fusion', model.ID); os.makedirs(out, exist_ok=True)
    open(os.path.join(out, f'{model.ID}.py'), 'w', encoding='utf-8').write(code)
    json.dump(MANIFEST, open(os.path.join(out, f'{model.ID}.manifest'), 'w'), indent=1)
    return os.path.join(out, f'{model.ID}.py')
